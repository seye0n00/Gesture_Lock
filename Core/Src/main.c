/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM2_Init();
  MX_I2C1_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */

  // 비밀번호 초기화
  Password_ResetInput();

  // 하드웨어 모듈 초기화
  Buzzer_Init();

  if (!IMU_Init())
  {
      Error_Handler();
  }


  if (!LockDisp_Init())
  {
      Error_Handler();
  }

  LockDisp_UpdateLock();
  LockDisp_UpdateInput();

  // LED 초기 상태 표시
  LED_SetState(lock_state);
  //Button_Init();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  Buzzer_Update();
	    // 1. 버튼 입력 처리
	    if (button_pressed)
	    {
	        button_pressed = false;
	        Buzzer_Stop();

	        // 잠금 상태: 비밀번호 검증
	        if (lock_state == eLOCK_STATE_LOCK)
	        {
	        	if (input_state == eINPUT_STATE_INPUT){
					if (Password_Check())
					{
						// 비밀번호 검증 성공
						lock_state = eLOCK_STATE_UNLOCK;
						input_state = eINPUT_STATE_SUCCESS;

						LED_SetState(lock_state);

						LockDisp_UpdateLock();
						LockDisp_UpdateInput();

						Buzzer_On(eINPUT_STATE_SUCCESS);
					}
					else
					{
						// 비밀번호 검증 실패
						input_state = eINPUT_STATE_FAILED;

						LockDisp_UpdateInput();
						Buzzer_On(eINPUT_STATE_FAILED);
					}

					// 검증 완료 후 기존 입력 제거
					Password_ResetInput();
				}
	        	else if (input_state == eINPUT_STATE_FAILED)
	        	{
	        	     // 버튼을 다시 누르면 재입력 시작
	        		 Password_ResetInput();
	        	     IMU_ResetGesture();

	        	     input_state = eINPUT_STATE_INPUT;
	        	     LockDisp_UpdateInput();
	        	 }
	        }

	        // 잠금 해제 상태: 다시 잠금
	        else if (lock_state == eLOCK_STATE_UNLOCK)
	        {
	            lock_state = eLOCK_STATE_LOCK;
	            input_state = eINPUT_STATE_INPUT;

	            Password_ResetInput();
	            IMU_ResetGesture();

	            LED_SetState(lock_state);

	            LockDisp_UpdateLock();
	            LockDisp_UpdateInput();
	        }
	    }

	    // 2. 잠금 상태에서만 IMU 입력 처리
	    if (lock_state == eLOCK_STATE_LOCK && input_state == eINPUT_STATE_INPUT)
	    {
	        eIMU_INPUT_DIRECT gesture;

	        if (IMU_Update(&gesture))
	        {
	            if (Password_AddInput(gesture))
	            {
	            	Buzzer_On(eINPUT_STATE_INPUT);

	                switch (gesture)
	                {
	                    case eIMU_INPUT_DIRECT_L:
	                    	LockDisp_NextInput("<-", 2);
	                        break;

	                    case eIMU_INPUT_DIRECT_R:
	                    	LockDisp_NextInput("->", 2);
	                        break;

	                    default:
	                        break;
	                }

	            }
	        }
	    }

	    HAL_Delay(10);

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

